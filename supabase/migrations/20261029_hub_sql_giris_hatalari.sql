-- Hub dakikada bir SQL hata günlüğündeki "Login failed" satırlarını okur
-- (lib/sql-giris-izleme.ts). Günlük ~1,5 gün geriye gidiyor (15 dk'lık
-- diferansiyel yedek satırları dolduruyor) — geçmiş yalnız burada kalır.
--
-- Bir satır = 5 dakikalık kovada aynı (kaynak IP, kullanıcı, neden, veritabanı)
-- ikilisinin sayısı. Ham günlük satırı saklanmaz. 90 günden eskiler silinir.
-- ============================================================================

create table if not exists hub.sql_giris_hatalari (
  id          bigint generated by default as identity primary key,
  kova        timestamptz not null,               -- 5 dk'ya hizalı
  ip          text        not null,
  kullanici   text        not null,
  neden       text        not null,               -- parola_yanlis | kullanici_yok | veritabani_acilamadi | giris_kapali | parola_suresi | diger
  veritabani  text        not null default '',    -- yalnız veritabani_acilamadi'da dolu
  adet        int         not null,
  ilk         timestamptz not null,
  son         timestamptz not null,
  unique (kova, ip, kullanici, neden, veritabani)
);
create index if not exists sql_giris_hatalari_son_idx on hub.sql_giris_hatalari (son);

-- Uyarı tekrarını önlemek için: anahtar = seviye|ip|kullanici|neden|veritabani
create table if not exists hub.sql_giris_bildirim (
  anahtar      text primary key,
  son_bildirim timestamptz not null
);

alter table hub.sql_giris_hatalari enable row level security;
drop policy if exists "hub authed full" on hub.sql_giris_hatalari;
create policy "hub authed full" on hub.sql_giris_hatalari
  for all to authenticated using (true) with check (true);

alter table hub.sql_giris_bildirim enable row level security;
drop policy if exists "hub authed full" on hub.sql_giris_bildirim;
create policy "hub authed full" on hub.sql_giris_bildirim
  for all to authenticated using (true) with check (true);

-- Kova ekleme: aynı kova tekrar gelirse adet toplanır (PostgREST upsert'i
-- üzerine yazar, toplamaz — bu yüzden RPC).
create or replace function hub.sql_giris_ekle(p jsonb)
returns void language sql as $$
  insert into hub.sql_giris_hatalari (kova, ip, kullanici, neden, veritabani, adet, ilk, son)
  select (x->>'kova')::timestamptz, x->>'ip', x->>'kullanici', x->>'neden',
         coalesce(x->>'veritabani', ''), (x->>'adet')::int,
         (x->>'ilk')::timestamptz, (x->>'son')::timestamptz
  from jsonb_array_elements(p) x
  on conflict (kova, ip, kullanici, neden, veritabani) do update
    set adet = hub.sql_giris_hatalari.adet + excluded.adet,
        ilk  = least(hub.sql_giris_hatalari.ilk, excluded.ilk),
        son  = greatest(hub.sql_giris_hatalari.son, excluded.son);
$$;

grant select, insert, update, delete on hub.sql_giris_hatalari, hub.sql_giris_bildirim to service_role, authenticated;
grant execute on function hub.sql_giris_ekle(jsonb) to service_role;

-- Özet: (ip, kullanıcı, neden, veritabanı) başına toplam — PostgREST 1000 satır
-- sınırına takılmasın diye toplama DB'de. p_gun_basi = gün kırılımı (Europe/Istanbul).
create or replace function hub.sql_giris_ozet(p_since timestamptz, p_gun_basi boolean default false)
returns table (gun date, ip text, kullanici text, neden text, veritabani text, adet bigint, son timestamptz)
language sql stable as $$
  select case when p_gun_basi then (kova at time zone 'Europe/Istanbul')::date end as gun,
         ip, kullanici, neden, veritabani, sum(adet)::bigint, max(son)
  from hub.sql_giris_hatalari
  where son >= p_since
  group by 1, ip, kullanici, neden, veritabani;
$$;
grant execute on function hub.sql_giris_ozet(timestamptz, boolean) to service_role;

-- Uyarı susturma (mobil Güvenlik sekmesinden). Kayıt yine tutulur, yalnız push gitmez.
-- kapsam: 'hepsi' | 'destek' (yalnız müdahale uyarıları) | 'k:<kullanıcı, küçük harf>'
create table if not exists hub.sql_giris_sustur (
  kapsam     text primary key,
  bitis      timestamptz not null,
  kim        text,
  olusturma  timestamptz not null default now()
);
alter table hub.sql_giris_sustur enable row level security;
drop policy if exists "hub authed full" on hub.sql_giris_sustur;
create policy "hub authed full" on hub.sql_giris_sustur
  for all to authenticated using (true) with check (true);
grant select, insert, update, delete on hub.sql_giris_sustur to service_role, authenticated;
